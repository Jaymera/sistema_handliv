export function stationRoom(station: {symbol?: string | null; assetType?: string | null}): RoomKind {
 const explicit: Record<string,RoomKind>={stock:'Ações',etf:'Ações',fii:'Ações',bdr:'Ações',reit:'Ações',forex:'Forex',crypto:'Crypto',commodity:'Commodities'};
 if(station.assetType && explicit[station.assetType]) return explicit[station.assetType];
 const symbol=(station.symbol??'').trim().toUpperCase();
 if(catalog[symbol])return catalog[symbol];
 // Only supported, unambiguous broker forms. Do not strip arbitrary prefixes/suffixes.
 if(/^(XAU|XAG)(USD|EUR)$/.test(symbol))return 'Commodities';
 const currencies=['USD','EUR','GBP','JPY','CHF','AUD','NZD','CAD','BRL'];
 if(symbol.length===6&&currencies.includes(symbol.slice(0,3))&&currencies.includes(symbol.slice(3))&&symbol.slice(0,3)!==symbol.slice(3))return 'Forex';
 if(/^(BTC|ETH|BNB|SOL|XRP|ADA|DOGE|DOT|MATIC|LINK)(USD|USDT)$/.test(symbol))return 'Crypto';
 return 'Outros';
}
